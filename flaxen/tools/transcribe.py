"""Notes straight from a recording, when there is no score -> score.js.

    python transcribe.py <audio> <out score.js> --segments "0.6:15.8,117.33:134"
        [--cuts "7.55 11.19 15.24"] [--beats-per-bar 3] [--midi transcribed.mid]
        [--min-velocity 0.42] [--min-length 0.1]

Runs Spotify's basic-pitch (ONNX model, no TensorFlow needed) to transcribe polyphonic
audio to notes, or reads a MIDI you already have (--midi). Keeps the notes inside the
audio segments that make up the excerpt, maps them to film time (segments are played
back to back in the order given, as the excerpt was cut), and splits them into voices:
voice 0 = the highest note of each attack (the melody, usually), voice 1 = the rest.

bars in score.js = 0 and the --cuts you give (the moments shots change), plus the end;
beats are spread evenly between them. Pitches are the recording's, not a score's: fine for
drawing, but spot-check the melody it prints against the music.

Install: pip install setuptools wheel && pip install --no-deps basic-pitch
         && pip install onnxruntime librosa pretty_midi mir_eval resampy
"""
import argparse, json, os
import pretty_midi

ap = argparse.ArgumentParser()
ap.add_argument('audio'); ap.add_argument('out')
ap.add_argument('--segments', required=True)
ap.add_argument('--cuts', default='')
ap.add_argument('--beats-per-bar', type=int, default=3)
ap.add_argument('--midi')
ap.add_argument('--min-velocity', type=float, default=0.42)
ap.add_argument('--min-length', type=float, default=0.1)
ap.add_argument('--flats', action='store_true', help='spell black keys as flats on the staff')
a = ap.parse_args()

if a.midi:
    midi = pretty_midi.PrettyMIDI(a.midi)
else:
    import basic_pitch
    from basic_pitch.inference import predict, Model
    model = Model(os.path.join(os.path.dirname(basic_pitch.__file__), 'saved_models/icassp_2022/nmp.onnx'))
    _, midi, _ = predict(a.audio, model, onset_threshold=0.5, frame_threshold=0.3, minimum_note_length=80)
    midi.write(os.path.splitext(a.out)[0] + '-transcribed.mid')

segs = [tuple(map(float, s.split(':'))) for s in a.segments.split(',')]
film0, offsets = 0.0, []
for s0, s1 in segs:
    offsets.append((s0, s1, film0 - s0))
    film0 += s1 - s0
duration = film0

raw = sorted([n for i in midi.instruments for n in i.notes if n.velocity / 127 >= a.min_velocity and n.end - n.start >= a.min_length], key=lambda n: n.start)
kept = []
for n in raw:
    for s0, s1, off in offsets:
        if s0 <= n.start < s1 - 0.02:
            kept.append((n.start + off, min(n.end, s1) + off, n.pitch, n.velocity / 127))
            break
# group simultaneous attacks; the top of each group is the melody
groups = []
for n in kept:
    if groups and n[0] - groups[-1][0][0] < 0.07:
        groups[-1].append(n)
    else:
        groups.append([n])
cuts = [0.0] + [float(x) for x in a.cuts.split()] + [duration]
bar_of = lambda t: max(i for i, c in enumerate(cuts[:-1]) if c <= t + 1e-6)
beats = []
for i in range(len(cuts) - 1):
    c0, c1 = cuts[i], cuts[i + 1]
    beats.append([round(c0 + (c1 - c0) * j / a.beats_per_bar, 3) for j in range(a.beats_per_bar + 1)])

notes = []
for g in groups:
    t = round(g[0][0], 3)
    top = max(g, key=lambda n: n[2])
    for n in sorted(g, key=lambda n: -n[2]):
        k = bar_of(t)
        beat_len = (cuts[k + 1] - cuts[k]) / a.beats_per_bar
        voice = 0 if n is top and n[2] >= 55 else 1
        notes.append([t, n[2], round((n[1] - n[0]) / beat_len, 3), voice, k, round((t - cuts[k]) / beat_len, 3)])

out = dict(bars=[round(c, 3) for c in cuts], beats=beats, notes=notes, duration=round(duration, 3))
if a.flats:
    out['spelling'] = 'flat'
open(a.out, 'w').write('// Generated by transcribe.py from the recording (pitches estimated by basic-pitch).\n'
                       '// notes: [film time, midi pitch, beats long, voice (0 = top line), shot, beat]\n'
                       'window.SCORE = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(f'{len(notes)} notes, {sum(1 for n in notes if n[3] == 0)} in the top line, film length {duration:.2f}s')
for n in notes:
    if n[3] == 0:
        print(f'  {n[0]:6.2f}  {pretty_midi.note_number_to_name(n[1])}')

"""Time every note of a score (MIDI) to the moment it is played in a recording -> js/score.js.

    python align_score.py <score.mid> <timing.json> <slots.json> <out score.js> [--beats-per-bar 3]

slots.json says which bars of the score make up the film and where they sit in the audio:
    [ {"score_bar": 0, "perf_bar": 0, "audio_to_film": 1.20}, ... ]
  score_bar      bar number in the MIDI (0-based)
  perf_bar       index into timing.json "bars" for the same bar in the recording (0-based)
  audio_to_film  seconds to subtract from audio time to get film time
                 (the start of your excerpt; for a spliced section, its own offset)
  length         optional bar length in seconds, for a final bar that rings on
                 (otherwise the next bar line in timing.json ends it)

Beats inside each bar snap to the nearest clear onset; each note then snaps (tightly) to the
nearest onset. Simultaneous notes share a time. Voices are the MIDI tracks/instruments in order
(0 = upper). Prints the upper voice so you can sanity-check against the score.

Output: window.SCORE = { bars: [film times of each slot's downbeat + the end],
                         beats: [[downbeat, beat 2, ..., next downbeat], ...],
                         notes: [[time, midi pitch, length in beats, voice, slot, beat], ...] }
Needs: pretty_midi.
"""
import argparse, json
import numpy as np
import pretty_midi

ap = argparse.ArgumentParser()
ap.add_argument('mid'); ap.add_argument('timing'); ap.add_argument('slots'); ap.add_argument('out')
ap.add_argument('--beats-per-bar', type=int, default=4)
a = ap.parse_args()
BPB = a.beats_per_bar

t = json.load(open(a.timing))
bars = t['bars']
onsets = [o for o in t['onsets'] if o[1] > 0.05]
slots = json.load(open(a.slots))


def nearest(x, win, strong=0.0):
    best = None
    for o in onsets:
        if abs(o[0] - x) <= win and o[1] >= strong and (best is None or abs(o[0] - x) < abs(best - x)):
            best = o[0]
    return best


beats = []
for s in slots:
    k = s['perf_bar']
    b0 = bars[k]
    b1 = b0 + s['length'] if 'length' in s else bars[k + 1] if k + 1 < len(bars) else b0 + (bars[k] - bars[k - 1])
    row = [b0]
    for j in range(1, BPB):
        g = b0 + (b1 - b0) * j / BPB
        row.append(nearest(g, 0.35 * (b1 - b0) / BPB, 0.15) or g)
    row.append(b1)
    beats.append(row)

m = pretty_midi.PrettyMIDI(a.mid)
mbeats = m.get_beats()
to_beat = lambda sec: float(np.interp(sec, mbeats, np.arange(len(mbeats)), right=len(mbeats) - 1 + (sec - mbeats[-1]) / (mbeats[-1] - mbeats[-2])))
notes = []
for voice, inst in enumerate(m.instruments):
    for n in inst.notes:
        b = to_beat(n.start)
        bar = int(b // BPB + 1e-6)
        slot = next((i for i, s in enumerate(slots) if s['score_bar'] == bar), None)
        if slot is None:
            continue
        beat = b - BPB * bar
        j = min(int(beat), BPB - 1)
        row = beats[slot]
        g = row[j] + (row[j + 1] - row[j]) * (beat - j)
        snap = nearest(g, 0.06 if abs(beat - round(beat)) > 1e-3 else 0.2)
        tt = (snap if snap is not None else g) - slots[slot]['audio_to_film']
        notes.append(dict(t=tt, pitch=n.pitch, dur=round(to_beat(n.end) - b, 3), voice=voice, slot=slot, beat=round(beat, 3)))

notes.sort(key=lambda n: (n['slot'], n['beat'], n['voice']))
for x, y in zip(notes, notes[1:]):
    if (x['slot'], x['beat']) == (y['slot'], y['beat']):
        y['t'] = x['t']

film_beats = [[round(x - slots[i]['audio_to_film'], 3) for x in row] for i, row in enumerate(beats)]
out = dict(bars=[row[0] for row in film_beats] + [film_beats[-1][-1]], beats=film_beats,
           notes=[[round(n['t'], 3), n['pitch'], n['dur'], n['voice'], n['slot'], n['beat']] for n in notes])
open(a.out, 'w').write('// Generated by align_score.py. notes: [time, midi pitch, beats long, voice, slot, beat]\n'
                       'window.SCORE = ' + json.dumps(out, separators=(',', ':')) + ';\n')
for n in notes:
    if n['voice'] == 0:
        print(f"slot {n['slot']} beat {n['beat']:<6} {pretty_midi.note_number_to_name(n['pitch']):<4} t={n['t']:.2f}")
print('bars', out['bars'])
